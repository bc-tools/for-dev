type NestedStrDictType = dict[
    str,
    NestedStrDictType | str
]


# ----------- #
# -- TOOLS -- #
# ----------- #

def build_parsers_needed(
    parsers_needed: set[ParserSpecs],
    yaml_specs    : NestedParserDictType,
) -> None:
    for k, v in yaml_specs.items():
        if isinstance(v, ParserSpecs):
            if v.module != TAG_STR:
                parsers_needed.add(v.module)

        else:
            build_parsers_needed(
                parsers_needed = parsers_needed,
                yaml_specs     = v,
            )


def prestr_2_pyvar(name):
    return f'@{name}@'


def get_pypsecs(
    yaml_specs: NestedParserDictType
) -> NestedStrDictType:
    pyspecs = dict()

    for k, v in yaml_specs.items():
        if isinstance(v, ParserSpecs):
            pyspecs[k] = {
                prestr_2_pyvar('TAG_PARSER'): prestr_2_pyvar(v.module),
                prestr_2_pyvar('TAG_USE_POST'): prestr_2_pyvar(v.use_post),
                prestr_2_pyvar('TAG_DATATYPE'): prestr_2_pyvar(
                    f'TAG_{v.datatype.upper()}'
                ),
            }

        else:
            pyspecs[k] = get_pypsecs(v)

    return pyspecs


