#!/usr/bin/env python3

from pathlib import Path
import              sys

sys.path.append(str(Path(__file__).parent.parent))

from cbutils.logconf    import *
from cbutils.pathplus   import *
from cbutils.coding_py  import *


import ast


# ------------------ #
# -- CONSTANTS #1 -- #
# ------------------ #

THIS_DIR    = Path(__file__).parent
PROJECT_DIR = THIS_DIR

while(PROJECT_DIR.name != 'aboutmeta'):
    PROJECT_DIR = PROJECT_DIR.parent

SPECS_DIR = PROJECT_DIR / 'src' / 'aboutmeta' / 'specs'

THIS_FILE_RELATIVE = (
      Path('aboutmeta')
    / Path(__file__).relative_to(PROJECT_DIR)
)


# ------------------ #
# -- CONSTANTS #2 -- #
# ------------------ #

DATA_EXPOSED = {
    'block': [
        'BLOCK_PARSERS',
        'BLOCK_STATUS',
        'BLOCK_ALTS',
    ],
    'flavour': 'FLAVOUR_SPECS',
    'parser': [
        'parse',
        'write',
        'post_prod*', # Only if it exists!
    ],
}


# ----------- #
# -- TOOLS -- #
# ----------- #

def expose_data(
    parent      : Path,
    tags        : set[str],
    names       : list[str],
    data_exposed: str | list[str],
) -> dict:
    specs = dict()

# Just one data exposed.
    if isinstance(data_exposed, str):
        data_exposed_builder = expose_one_data

# Several data exposed.
    else:
        data_exposed_builder = expose_several_data

# Let's go!
    for n in names:
        specs[
            prestr_2_pyvar(get_tag(n))
        ] = data_exposed_builder(
            parent       = parent,
            tags         = tags,
            name         = n,
            data_exposed = data_exposed,
        )

    return specs


def expose_one_data(
    parent      : Path,
    tags        : set[str],
    name        : str,
    data_exposed: str,
) -> str:
    return prestr_2_pyvar(f'{name}.{data_exposed}')


def expose_several_data(
    parent      : Path,
    tags        : set[str],
    name        : str,
    data_exposed: list[str],
) -> dict[str, str]:
    local_api = dict()

    for de in data_exposed:
        if de[-1] == '*':
            de = de[:-1]

# Do we have to add this optional data exposed?
            if not file_has_attr(
                parent    = parent,
                name      = name,
                attr_name = de,
            ):
                break

# Let's add a new data exposed.
        tags.add(de)

        local_api[
            prestr_2_pyvar(get_tag(de))
        ] = expose_one_data(
            parent       = parent,
            tags         = tags,
            name         = name,
            data_exposed = de,
        )

    return local_api


def file_has_attr(
    parent   : Path,
    name     : str,
    attr_name: str,
) -> bool:
    file  = parent / f'{name}.py'
    code  = file.read_text()
    pyast = ast.parse(code)

    for node in ast.iter_child_nodes(pyast):
         if isinstance(node, ast.FunctionDef):
            if attr_name == node.name:
                return True

         if (
            isinstance(node, ast.Name)
            and
            isinstance(node.ctx, ast.Store)
         ):
            if attr_name == node.name:
                return True

    return False


# ----------------- #
# -- LET'S WORK! -- #
# ----------------- #

logging.info(f"Working on 'user friendly API'.")

for kind_folder in SPECS_DIR.glob('*'):
    if (
        kind_folder.name.startswith('_')
        or
        not kind_folder.is_dir()
    ):
        continue

    kind = kind_folder.name

    if kind == 'data':
        continue

    KIND = kind.upper()

    logging.info(f"Analyzing 'aboutmeta/specs/{kind}' folder.")

    all_kind_names = []

    for p in kind_folder.glob('*.py'):
        kind_name = p.stem

        if kind_name.startswith('__'):
            continue

        all_kind_names.append(kind_name)

    all_kind_names.sort()

# Let's build the Python code.
    imports_need = ', '.join(all_kind_names)

    tags = set(all_kind_names)

    pyspecs = expose_data(
        parent       = kind_folder,
        tags         = tags,
        names        = all_kind_names,
        data_exposed = DATA_EXPOSED[kind],
    )

    pytags = '\n'.join(
        f'{get_tag(f)} = "{f}"'
        for f in sorted(tags)
    )

    pycode = f'''
{SHEBANG_PYTHON}

# File automatically generated by
# '{THIS_FILE_RELATIVE}'

{magic_title('IMPORTS')}

from aboutmeta.specs.{kind} import {imports_need}


{magic_title(f'ALL {KIND} SPECS')}

{pytags}

ALL_{KIND}S = {pyspecs}
    '''.strip() + '\n'

    pycode = normalize_prestr_2_pyvar(
        pycode
    )

    add_black_pyfile(
        code = pycode,
        file = kind_folder / f'__ALL_{KIND}S__.py'
    )
