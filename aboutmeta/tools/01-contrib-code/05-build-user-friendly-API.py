#!/usr/bin/env python3

from pathlib import Path
import              sys

sys.path.append(str(Path(__file__).parent.parent))

from cbutils.logconf    import *
from cbutils.pathplus   import *
from cbutils.coding_py  import *


# ------------------ #
# -- CONSTANTS #1 -- #
# ------------------ #

THIS_DIR    = Path(__file__).parent
PROJECT_DIR = THIS_DIR

while(PROJECT_DIR.name != 'aboutmeta'):
    PROJECT_DIR = PROJECT_DIR.parent

SPECS_DIR = PROJECT_DIR / 'src' / 'aboutmeta' / 'specs'

THIS_FILE_RELATIVE = (
      Path('aboutmeta')
    / Path(__file__).relative_to(PROJECT_DIR)
)


# ------------------ #
# -- CONSTANTS #2 -- #
# ------------------ #



# ----------- #
# -- TOOLS -- #
# ----------- #



# ----------------- #
# -- LET'S WORK! -- #
# ----------------- #

logging.info(f"Working on 'user friendly API'.")

for special_dir in SPECS_DIR.glob('*'):
    if (
        special_dir.name.startswith('_')
        or
        not special_dir.is_dir()
    ):
        continue

    kind = special_dir.name

    if kind == 'data':
        continue

    KIND = kind.upper()

    logging.info(f"Analyzing 'aboutmeta/specs/{kind}' folder.")

    exit()


    pyfile = special_dir / f'__ALL_{KIND}S__.py'
    pyfile.touch()






TAG_FLAVOUR_SPECS = 'FLAVOUR_SPECS'

CONTEXT  = 'flavour'

FLAVOUR_DIR         = SPECS_DIR / CONTEXT





all_flavours = []

for p in FLAVOUR_DIR.glob('*.py'):
    flavour_name = p.stem

    if flavour_name.startswith('__'):
        continue

    all_flavours.append(p.stem)

all_flavours.sort()


pytags = '\n'.join(
    f'{get_tag(f)} = "{f}"'
    for f in all_flavours
)


pyspecs = dict()

for f in all_flavours:
    pyspecs[
        prestr_2_pyvar(get_tag(f))
    ] = prestr_2_pyvar(
        f'{f}.FLAVOUR_SPECS'
    )

# Let's build the Python code.
imports_need = ', '.join(all_flavours)

all_flavours_pycode = f'''
{SHEBANG_PYTHON}

# File automatically generated by
# '{THIS_FILE_RELATIVE}'

{magic_title('IMPORTS')}

from aboutmeta.specs.flavour import {imports_need}


{magic_title('ALL FLAVOUR SPECS')}

{pytags}

ALL_FLAVOURS = {pyspecs}
        '''.strip() + '\n'

all_flavours_pycode = normalize_prestr_2_pyvar(
    all_flavours_pycode
)

add_black_pyfile(
    code = all_flavours_pycode,
    file = ALL_FLAVOURS_PYFILE
)
