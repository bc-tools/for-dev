#!/usr/bin/env python3

from pathlib import Path
import              sys

sys.path.append(str(Path(__file__).parent.parent))


from cbutils.logconf    import *
from cbutils.pathplus   import *
from cbutils.coding_py  import *
from cbutils.contrib    import *

from projutils.constants.yaml_specs import SYMBOL_OPTIONAL


# --------------- #
# -- CONSTANTS -- #
# --------------- #

CONTEXT  = 'flavour'
MSG_CTXT = f'{CONTEXT} config contrib'


THIS_DIR    = Path(__file__).parent
PROJECT_DIR = THIS_DIR

while(PROJECT_DIR.name != 'aboutmeta'):
    PROJECT_DIR = PROJECT_DIR.parent

SPECS_DIR   = PROJECT_DIR / 'src' / 'aboutmeta' / 'specs'
FLAVOUR_DIR = SPECS_DIR / CONTEXT
CONTRIB_DIR = (
      PROJECT_DIR / 'contribute' / 'api'
    / 'block-n-flavour' / CONTEXT
)

THIS_FILE_RELATIVE = (
      Path('aboutmeta')
    / Path(__file__).relative_to(PROJECT_DIR)
)

CONTRIB_CFG_DIR_RELATIVE = (
      Path('aboutmeta')
    / CONTRIB_DIR.relative_to(PROJECT_DIR)
    / 'config'
)


# ----------------- #
# -- LET'S WORK! -- #
# ----------------- #

for _ in [
    empty_dir,
    add_missing_init,
]:
    _(FLAVOUR_DIR)


for folder, contribs in get_accepted_paths(
    context     = CONTEXT,
    contrib_dir = CONTRIB_DIR
).items():
    ctxt = folder.parent.name

    logging.info(f"Working on '{ctxt}' configs.")

    for one_contrib in contribs:
        logging.info(f"Analyzing '{one_contrib}'.")

        contrib_file = folder / one_contrib

        spec_list = safe_load(contrib_file.read_text())

        pyspecs = dict()

        for parser_spec in spec_list:
            parser_spec = parser_spec.strip()

            if parser_spec[-1] == SYMBOL_OPTIONAL:
                is_optional = True
                parser_spec = parser_spec[:-1].strip()

            else:
                is_optional = False

            if parser_spec in pyspecs:
                raise ValueError(
                    f'repeated value {parser_spec!r} in the list '
                     'defining the flavour.'
                )

            spec = {
                prestr_2_pyvar(f'TAG_{k}'): prestr_2_pyvar(
                    f'{parser_spec}.{k}'
                )
                for k in [
                    'BLOCK_PARSERS',
                    'BLOCK_STATUS',
                    'BLOCK_ALTS',
                ]
            }

            spec[prestr_2_pyvar('TAG_IS_MANDATORY')] = not is_optional

            pyspecs[parser_spec] = spec

# Let's build the Python code.
        imports_need = ', '.join(sorted(pyspecs))

        flavour_spec_pycode = f'''
{SHEBANG_PYTHON}

# File automatically generated by
# '{THIS_FILE_RELATIVE}'
#
# This block is maintained inside the file
# '{CONTRIB_CFG_DIR_RELATIVE / one_contrib}'

{magic_title('IMPORTS')}

from aboutmeta.core.constants.internal_tags import *

from aboutmeta.specs.block import {imports_need}


{magic_title('FLAVOUR SPECS')}

FLAVOUR_SPECS = {pyspecs}
        '''.strip() + '\n'

        flavour_spec_pycode = normalize_prestr_2_pyvar(
            flavour_spec_pycode
        )

        add_black_pyfile(
            code = flavour_spec_pycode,
            file = FLAVOUR_DIR / f'{pysuglify(contrib_file.stem)}.py'
        )
